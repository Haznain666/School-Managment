-- sequence_order defaults to 0, which would put every existing term joint
-- first and let the list order itself arbitrarily. The order a school already
-- reads its terms in is the order of their start dates, so that is what this
-- writes: First Term, Second Term, Final Term, exactly as they were.
--
-- created_at breaks a tie between two terms that start on the same day, so the
-- result is stable rather than whatever the planner returned that afternoon.
UPDATE "exam_terms"
SET "sequence_order" = ordered."rn"
FROM (
	SELECT
		"id",
		row_number() OVER (
			PARTITION BY "location_id", "academic_year_id"
			ORDER BY "start_date", "created_at"
		) AS "rn"
	FROM "exam_terms"
) AS ordered
WHERE "exam_terms"."id" = ordered."id"
	AND "exam_terms"."sequence_order" = 0;--> statement-breakpoint

-- Every existing school gets the four sub-categories a new one is seeded with.
-- The list is DEFAULT_SUBCATEGORIES in db/schema/result-subcategories.ts and
-- lib/school-bootstrap.ts gives the same four to every school created after
-- this runs -- a school provisioned on either side of this migration has to
-- behave identically.
--
-- Green through red, best to worst, because that is the order a teacher reads a
-- picker in and a parent reads a legend in. A school that words its judgements
-- differently renames them; the point of seeding is that the descriptor screen
-- opens with something in it rather than an empty state and a shrug.
INSERT INTO "result_subcategories" ("location_id", "label", "color_hex", "sort_order")
SELECT
	s."location_id",
	seed."label",
	seed."color_hex",
	seed."sort_order"
FROM "schools" s
CROSS JOIN (VALUES
	('Exceeding',         '#22C55E', 0),
	('Satisfactory',      '#3B82F6', 1),
	('Emerging',          '#F59E0B', 2),
	('Needs Improvement', '#EF4444', 3)
) AS seed("label", "color_hex", "sort_order")
ON CONFLICT DO NOTHING;
