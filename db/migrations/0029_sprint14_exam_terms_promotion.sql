-- Sprint 14 -- Exam terms, per-grade datesheets, promotion criteria, results.
--
-- Seven tables, eleven columns and one relaxed CHECK. The shape of the sprint
-- is that a term stops being a window with exams hung off it and becomes a
-- *heading* over one or more datesheets, because the infant school and the
-- senior school do not sit "First Term" on the same days and never did.
--
-- ── Why exam_terms.start_date became nullable ───────────────────────────
-- The authoritative dates moved down to exam_schedules, where they can differ
-- per grade. The term keeps an optional envelope for calendar views, and every
-- term that exists today keeps the dates it was created with -- nothing is
-- cleared. Where it is blank the UI shows the earliest start and the latest end
-- across the term's schedules.
--
-- ── Why exam_schedule_grades carries term_id ────────────────────────────
-- The rule is "a grade sits at most one datesheet per term", and that is a
-- uniqueness constraint spanning the term, not the schedule. Without the column
-- it is an application check that two concurrent requests both pass, leaving a
-- class on two datesheets and the generate step writing two sets of papers for
-- the same children. Archiving a schedule MUST archive its grade rows in the
-- same transaction or the grade stays locked out by an index nobody can see.
--
-- ── Why exam_results_marks_check had to be relaxed ──────────────────────
-- The old rule was "absent with no mark, or present with a mark". In descriptor
-- mode the child was present and there is no mark, so the only valid descriptor
-- row was unwritable. The new rule keeps the fact that mattered -- an absence
-- never carries a mark -- and drops the one that stopped holding the moment a
-- result could be a word instead of a number.
--
-- exam_subjects.max_marks is deliberately NOT relaxed. It stays NOT NULL with
-- its > 0 CHECK, and the generate step writes 1/0 for a descriptor paper that
-- no descriptor code path ever reads. Relaxing it would put a null denominator
-- inside every percentage the marks path computes, to save two literals.
--
-- ── student_term_results is not promotion_runs ──────────────────────────
-- promotion_runs is enrolment plumbing: which section a child sits in next
-- September. student_term_results.final_status is the academic judgement: did
-- this child pass. Different facts, different people, different moments. This
-- migration does not merge them and no later one should.
--
-- ── The permission CHECK ────────────────────────────────────────────────
-- Dropped and recreated with results.promotion, which is what adding any
-- permission key costs -- the constraint is generated from the PERMISSIONS
-- array in lib/permissions.ts (STATE.md §5aa). No role_permissions rows are
-- inserted: that table holds *overrides*, and seeding it would freeze the three
-- roles' access at today's answer. The grant lives in DEFAULT_ROLE_PERMISSIONS,
-- exactly as 0027 did for the three accounting keys.
--
-- ── The four hand-written parts ─────────────────────────────────────────
-- Everything between the PRE-FLIGHT and SEED dividers is generated by
-- drizzle-kit from the schema files, so this file and the snapshot in meta/
-- cannot disagree. The two hand-written blocks are:
--
--   PRE-FLIGHT  trims any term name longer than the new 50-character CHECK
--               allows. The API used to accept 80, so a school that used them
--               would otherwise have this migration fail on ALTER TABLE ...
--               ADD CONSTRAINT with a message naming neither the row nor why.
--   SEED        backfills exam_terms.sequence_order from the dates each term
--               already has, and gives every existing school the four default
--               result sub-categories a new school is seeded with.
--
-- Both are idempotent. Running this twice writes nothing the second time.

