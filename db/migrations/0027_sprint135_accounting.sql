-- ── The backfill ────────────────────────────────────────────────────────
-- Every fee payment ever recorded becomes a posting. Without this the ledger
-- opens empty at a school that has been taking money for a year, its Cash in
-- Hand reads zero, and the first person to look at a balance sheet concludes
-- the module does not work.
--
-- entry_date is the payment date, not today: a backfill dated the day of the
-- migration would put a year of takings on one afternoon's day book.
INSERT INTO "ledger_transactions" (
	"location_id", "entry_date", "memo", "source", "source_id",
	"reference_number", "created_by_uid", "created_at"
)
SELECT
	payment."location_id",
	payment."payment_date",
	'Fee payment (backfilled from the fee module)',
	'fee_payment',
	payment."id",
	payment."reference_number",
	payment."collected_by_uid",
	payment."created_at"
FROM "fee_payments" payment
WHERE payment."ledger_transaction_id" IS NULL
	AND EXISTS (
		SELECT 1 FROM "ledger_accounts" a
		WHERE a."location_id" = payment."location_id" AND a."system_key" = 'fee_income'
	);--> statement-breakpoint

-- Two lines each: the account the money landed in, and Fee Income. A cheque
-- goes to 1020 rather than 1010 -- a cheque is not money until it clears, and a
-- school counting it as bank balance will overdraw on one that bounces.
--
-- Backfilled cash goes to office cash rather than to the collector's own
-- account: per-staff accounts do not exist yet at the moment this runs, and
-- inventing one retrospectively would open every clerk's balance with a year of
-- takings they settled long ago.
INSERT INTO "ledger_entries" (
	"location_id", "transaction_id", "account_id", "debit", "credit", "memo", "created_at"
)
SELECT
	txn."location_id",
	txn."id",
	side."account_id",
	side."debit",
	side."credit",
	side."memo",
	txn."created_at"
FROM "ledger_transactions" txn
JOIN "fee_payments" payment ON payment."id" = txn."source_id"
JOIN LATERAL (
	SELECT
		landing."id" AS "account_id",
		payment."amount" AS "debit",
		0::numeric AS "credit",
		'Money received'::text AS "memo"
	FROM "ledger_accounts" landing
	WHERE landing."location_id" = txn."location_id"
		AND landing."system_key" = CASE payment."payment_method"
			WHEN 'bank_transfer' THEN 'bank'
			WHEN 'cheque' THEN 'cheques_in_hand'
			ELSE 'cash_in_hand'
		END
	UNION ALL
	SELECT
		income."id",
		0::numeric,
		payment."amount",
		'Fee income'::text
	FROM "ledger_accounts" income
	WHERE income."location_id" = txn."location_id"
		AND income."system_key" = 'fee_income'
) side ON TRUE
WHERE txn."source" = 'fee_payment'
	AND NOT EXISTS (
		SELECT 1 FROM "ledger_entries" e WHERE e."transaction_id" = txn."id"
	);--> statement-breakpoint

-- And the link back, which is what stops the backfill running twice.
UPDATE "fee_payments" payment
SET "ledger_transaction_id" = txn."id"
FROM "ledger_transactions" txn
WHERE txn."source" = 'fee_payment'
	AND txn."source_id" = payment."id"
	AND payment."ledger_transaction_id" IS NULL;
