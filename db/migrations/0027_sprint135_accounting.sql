-- Sprint 13.5 -- Accounting: the ledger, expenses, and per-staff cash.
--
-- Six tables and one column, and the column is the point of the sprint:
-- fee_payments.ledger_transaction_id is what makes money the school has
-- already taken part of the same books as the money it spends.
--
-- ── APPEND-ONLY ─────────────────────────────────────────────────────────
-- ledger_transactions and ledger_entries are never updated and never deleted,
-- by this application or by anybody reading this file later. A correction is a
-- second transaction whose lines are the mirror of the first, carrying
-- reverses_transaction_id, and both stay in the book. Sprint 16's parent wallet
-- and Sprint 20's POS post here, so the rule has to hold before real money
-- arrives rather than be retrofitted underneath it.
--
-- ── Income is recognised when the money is received, not when it is billed ──
-- A fee payment posts: debit the account the money landed in, credit 4000 Fee
-- Income. Raising a challan posts nothing.
--
-- That is a cash-basis decision and it is deliberate. The accrual alternative
-- -- debit 1100 Fees Receivable on issue, clear it on payment -- would put
-- eight hundred transactions in the day book every time a school bulk-generates
-- a month's challans, and would give the school two answers to "how much is
-- outstanding": the ledger's, and the fee module's. The fee module's is the one
-- with a challan number attached to every rupee of it, so it stays
-- authoritative and the aged-debt report keeps reading it.
--
-- 1100 Fees Receivable is still seeded, because a school moving its books in
-- here needs somewhere to put the fees that were already owed on the day it
-- started. It is reached by journal entry, not by the fee module.
--
-- ── Per-staff cash accounts ─────────────────────────────────────────────
-- A cash payment does not land in the office safe. It lands in the drawer of
-- whoever took it, and that is a different fact. Each person who takes money
-- gets their own asset account (ledger_accounts.owner_user_id); settling is a
-- transaction moving the balance to office cash, and their balance in between
-- is what they owe the school right now. See db/schema/cash-settlements.ts.
--
-- ── The permission CHECK ────────────────────────────────────────────────
-- Dropped and recreated with accounting.read / .write / .settle, which is what
-- adding any permission key costs -- the constraint is generated from the
-- PERMISSIONS array in lib/permissions.ts (STATE.md §5aa).
--
-- ── The three hand-written parts ────────────────────────────────────────
-- Everything above the "SEED" divider is generated by drizzle-kit from the
-- schema files, so this file and the snapshot in meta/ cannot disagree.
-- Everything below it is hand-written and is the part that has to be read:
-- the chart of accounts every existing school gets, its expense categories,
-- and the backfill of every fee payment ever recorded into the ledger.
--
-- The backfill is guarded rather than assumed. It posts only for schools that
-- came out of the seed with a Fee Income account, and only for payments that
-- do not already carry a posting -- so running it twice writes nothing the
-- second time.

