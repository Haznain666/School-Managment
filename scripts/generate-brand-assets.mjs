#!/usr/bin/env node

/**
 * Regenerates `lib/brand-assets-data.ts` from `public/brand/`.
 *
 *   node scripts/generate-brand-assets.mjs
 *
 * ── Why the platform's logo is compiled into a module ────────────────────
 * Two server-side things need the SchoolHub marks as *bytes*, not as a URL:
 * the invoice PDF (`lib/platform-invoice-pdf.ts`) and the platform favicon
 * (`app/icon/[size]/route.ts`). Reading `public/brand/*.png` from disk at
 * runtime works on a developer's machine and fails on a standalone build,
 * where `public/` is only there if the deploy remembered to copy it —
 * DEPLOYMENT.md §1 says it must be copied by hand, and §5b records a workflow
 * that copied it only "if it ever exists". A PDF with a missing logo is a
 * degraded document nobody reports; an import cannot go missing.
 *
 * Downscaled first, so the module stays small: the originals are 1774px and
 * ~300 KB, and neither a 48pt-high PDF header nor a 512px icon needs that.
 * Screens keep using the full-size files through `next/image`.
 */

import { readFileSync, writeFileSync } from 'node:fs';

import sharp from 'sharp';

const logo = await sharp(readFileSync('public/brand/schoolhub-logo.png'))
  .resize({ width: 600 })
  .png({ compressionLevel: 9, palette: true })
  .toBuffer();

const mark = await sharp(readFileSync('public/brand/schoolhub-mark.png'))
  .resize({ width: 320 })
  .png({ compressionLevel: 9, palette: true })
  .toBuffer();

const logoMeta = await sharp(logo).metadata();
const markMeta = await sharp(mark).metadata();

const body = `/**
 * GENERATED by \`scripts/generate-brand-assets.mjs\` — do not edit by hand.
 *
 * The SchoolHub word mark and eyes mark, downscaled and base64-encoded, for the
 * two server-side consumers that need bytes rather than a URL. See the script's
 * header for why these are compiled in rather than read from \`public/\`.
 */

/** ${String(logoMeta.width)}×${String(logoMeta.height)} PNG. */
export const SCHOOLHUB_LOGO_PNG_BASE64 =
  '${logo.toString('base64')}';

export const SCHOOLHUB_LOGO_SIZE = { width: ${String(logoMeta.width)}, height: ${String(logoMeta.height)} } as const;

/** ${String(markMeta.width)}×${String(markMeta.height)} PNG. */
export const SCHOOLHUB_MARK_PNG_BASE64 =
  '${mark.toString('base64')}';

export const SCHOOLHUB_MARK_SIZE = { width: ${String(markMeta.width)}, height: ${String(markMeta.height)} } as const;
`;

writeFileSync('lib/brand-assets-data.ts', body);
console.log(
  `lib/brand-assets-data.ts written — logo ${String(logo.length)} bytes, mark ${String(mark.length)} bytes`,
);
